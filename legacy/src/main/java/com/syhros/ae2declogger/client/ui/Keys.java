package com.syhros.ae2declogger.client.ui;

/** Key codes the shared screens understand; each host maps its version's key codes to these. */
public final class Keys {

    public static final int OTHER = 0;
    public static final int ESCAPE = 1;
    public static final int BACKSPACE = 2;
    public static final int ENTER = 3;
    public static final int TAB = 4;
    public static final int DELETE = 5;
    /** The F key (Ctrl+F focuses search). */
    public static final int F = 6;
    /** Number keys 1 to 9 are DIGIT_1 + n - 1. */
    public static final int DIGIT_1 = 11;

    private Keys() {
    }
}
